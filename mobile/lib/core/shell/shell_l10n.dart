/// Reads [LocalizationService] safely whether mounted under [Provider] or standalone.
LocalizationService? maybeLocalizationOf(
  BuildContext context, {
  bool listen = true,
}) {
  try {
    return Provider.of<LocalizationService>(context, listen: listen);
  } catch (_) {
    return null;
  }
}

/// Resolves localized label without returning raw snake_case keys or throwing in tests.
String shellTr(BuildContext context, String key, {String? fallback}) {
  LocalizationService? loc = maybeLocalizationOf(context, listen: true);
  loc ??= maybeLocalizationOf(context, listen: false);
  if (loc != null) {
    final translated = loc.translate(key);
    if (translated != key) return translated;
    final extras = loc.currentLanguage == AppLanguage.georgian
        ? _kaShellExtras
        : _enShellExtras;
    if (extras.containsKey(key)) return extras[key]!;
  }
  return fallback ?? key;
}

/// Formats [dt] with localized short month name and HH:mm without Intl locale crashes.
String formatShellDateTime(BuildContext context, DateTime dt) {
  final loc = maybeLocalizationOf(context, listen: false);
  final isKa = loc?.currentLanguage == AppLanguage.georgian;
  const kaMonths = <String>[
    'იან',
    'თებ',
    'მარ',
    'აპრ',
    'მაი',
    'ივნ',
    'ივლ',
    'აგვ',
    'სექ',
    'ოქტ',
    'ნოე',
    'დეკ',
  ];
  const enMonths = <String>[
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
  final month = (isKa ? kaMonths : enMonths)[dt.month - 1];
  final hh = dt.hour.toString().padLeft(2, '0');
  final mm = dt.minute.toString().padLeft(2, '0');
  return isKa
      ? '${dt.day} $month, ${dt.year} · $hh:$mm'
      : '$month ${dt.day}, ${dt.year} · $hh:$mm';
}
